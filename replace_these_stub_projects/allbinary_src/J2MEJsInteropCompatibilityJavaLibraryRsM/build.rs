// Generates the module tree for the generated Rust sources.
// Each Java package directory becomes a module and each .rs file becomes a module with the class name.
// The library sources and the dependency sources are merged into one tree because the generated code uses crate:: paths for both.
// Dependency source directories are separated with ; in ALLBINARY_RUST_DEPENDENCY_SOURCE_PATHS.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const DEPENDENCY_SOURCE_PATHS: &str = "ALLBINARY_RUST_DEPENDENCY_SOURCE_PATHS";

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "box", "break", "const", "continue", "dyn", "else", "enum", "extern", "false", "fn", "for", "gen",
    "if", "impl", "in", "let", "loop", "macro", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct",
    "trait", "true", "try", "type", "typeof", "unsafe", "use", "where", "while", "yield", "abstract", "become", "do", "final",
    "override", "priv", "unsized", "virtual",
];

#[derive(Default)]
struct ModuleTree {
    children: BTreeMap<String, ModuleTree>,
    files: BTreeMap<String, PathBuf>,
}

fn add_sources(tree: &mut ModuleTree, dir: &Path) {
    let mut entries: Vec<PathBuf> = match fs::read_dir(dir) {
        Ok(entries) => entries.filter_map(|entry| entry.ok().map(|entry| entry.path())).collect(),
        Err(error) => {
            println!("cargo:warning=Could not read Rust source directory {}: {}", dir.display(), error);
            return;
        }
    };
    entries.sort();
    for path in entries {
        let name = match path.file_stem() {
            Some(name) => name.to_string_lossy().to_string(),
            None => continue,
        };
        if path.is_dir() {
            add_sources(tree.children.entry(name).or_default(), &path);
        } else if path.extension().map_or(false, |extension| extension == "rs") {
            if let Some(existing) = tree.files.insert(name, path.clone()) {
                println!("cargo:warning=Rust module {} replaces {}", path.display(), existing.display());
            }
        }
    }
}

fn identifier(name: &str) -> String {
    if KEYWORDS.contains(&name) {
        format!("r#{}", name)
    } else {
        name.to_string()
    }
}

fn write_tree(tree: &ModuleTree, indent: usize, output: &mut String) {
    let spaces = "    ".repeat(indent);
    for (name, path) in &tree.files {
        let path = path.to_string_lossy().replace('\\', "/");
        output.push_str(&format!("{}#[path = {:?}]\n{}pub mod {};\n", spaces, path, spaces, identifier(name)));
    }
    for (name, child) in &tree.children {
        if child.files.is_empty() && child.children.is_empty() {
            continue;
        }
        output.push_str(&format!("{}pub mod {} {{\n", spaces, identifier(name)));
        write_tree(child, indent + 1, output);
        output.push_str(&format!("{}}}\n", spaces));
    }
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let mut source_dirs = vec![manifest_dir.join("src").join("main").join("java")];

    println!("cargo:rerun-if-env-changed={}", DEPENDENCY_SOURCE_PATHS);
    if let Ok(paths) = env::var(DEPENDENCY_SOURCE_PATHS) {
        for path in paths.split(';').map(str::trim).filter(|path| !path.is_empty()) {
            let dir = PathBuf::from(path);
            if dir.is_dir() {
                source_dirs.push(dir);
            } else {
                println!("cargo:warning=Rust dependency source directory does not exist: {}", dir.display());
            }
        }
    }

    let mut tree = ModuleTree::default();
    for dir in &source_dirs {
        println!("cargo:rerun-if-changed={}", dir.display());
        add_sources(&mut tree, dir);
    }

    let mut output = String::from("// Generated by build.rs from the Java package directories\n");
    write_tree(&tree, 0, &mut output);

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("modules.rs"), output).expect("write modules.rs");
}
